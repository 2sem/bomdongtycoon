    s.ellipse(7.6, 7.6, 4.2, 4.2, "gold")
    s.ellipse(6, 5.5, 2.2, 1.2, "gold_light")
    s.px(3, 7, "gold_light"), s.px(3, 8, "gold_light"), s.px(4, 5, "gold_light")
