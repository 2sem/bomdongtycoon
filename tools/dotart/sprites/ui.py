def slice9(fill, border="ink", hi=None, lo=None, lip=None, lip_h=0, drop=0, open_bottom=False):
    """24x24 source with 8px caps. `lip` is a darker band along the bottom that
    makes a button look raised; `drop` shifts the face down for the pressed state."""
    s = Sprite(24, 24)
    top, bottom = drop, 23
    s.rect(2, top + 1, 20, bottom - top - 1, fill)
    s.rect(1, top + 2, 22, bottom - top - 3, fill)
    if lip:
        s.rect(1, bottom - 1 - lip_h, 22, lip_h, lip)
        s.rect(2, bottom - 1, 20, 1, lip)
    if hi:
        s.hline(3, top + 2, 18, hi), s.vline(2, top + 3, bottom - top - 6 - lip_h, hi)
    if lo:
        s.hline(3, bottom - 2 - lip_h, 18, lo)
        s.vline(21, top + 3, bottom - top - 5 - lip_h, lo)
    s.hline(3, top, 18, border), s.hline(3, bottom, 18, border)
    s.vline(0, top + 3, bottom - top - 5, border), s.vline(23, top + 3, bottom - top - 5, border)
    for x, y in ((1, top + 2), (2, top + 1), (21, top + 1), (22, top + 2),
                 (1, bottom - 2), (2, bottom - 1), (21, bottom - 1), (22, bottom - 2)):
        s.px(x, y, border)
    for x, y in ((1, top + 1), (22, top + 1), (1, bottom - 1), (22, bottom - 1)):
        s.px(x, y, None)
    if open_bottom:
        s.rect(1, 20, 22, 4, fill)
        s.vline(0, 20, 4, border), s.vline(23, 20, 4, border)
        if hi:
            s.vline(2, 18, 6, hi)
        if lo:
            s.vline(21, 18, 6, lo)
    return s


def bar_frame():
    s = Sprite(16, 8)
    s.rect(1, 0, 14, 8, "ink"), s.rect(0, 1, 16, 6, "ink")
    s.rect(2, 2, 12, 4, "plum")
    s.hline(2, 2, 12, "ink")
    return s


def bar_fill(base, light, dark):
    s = Sprite(6, 4, base)
    s.hline(0, 0, 6, light), s.hline(0, 3, 6, dark)
    s.px(5, 1, dark), s.px(5, 2, dark)
    return s


def mascot(w, h, size):
    """Rosette with a face; the pale heart is widened so the face has room."""
    s = rosette(w, h, GREEN, 9, 6, outline=False, ribs=True)
    cx, cy = s.w // 2, s.h // 2
    s.ellipse(cx, cy + 1, w * 0.3, h * 0.27, "leaf_light")
    s.ellipse(cx, cy + 0.5, w * 0.26, h * 0.22, "leaf_pale")
    face(s, cx, cy, big=True)
    s.outline("ink")
    out = Sprite(size, size)
    return out.blit(s, (size - s.w) // 2, (size - s.h) // 2)


def logo():
    s = mascot(42, 34, 48)
    for x, y in ((3, 6), (44, 9), (41, 42)):
        s.px(x, y, "paper"), s.px(x - 1, y, "gold_light"), s.px(x + 1, y, "gold_light")
        s.px(x, y - 1, "gold_light"), s.px(x, y + 1, "gold_light")
    return s


